#!/usr/bin/env bash
# Render Quickshell's current colors for new kitty windows, then update open ones.
set -euo pipefail

mode=$1 background=$2 foreground=$3
case "$mode" in
    white|black|red) ;;
    *) exit 1 ;;
esac
[[ $background =~ ^#[0-9a-fA-F]{6}$ && $foreground =~ ^#[0-9a-fA-F]{6}$ ]] || exit 1

# Light mode stays opaque; dark mode keeps the existing transparency.
opacity=0.85
[[ $mode == white ]] && opacity=1.0

# Light and dark are monochrome: each ANSI hue is its own gray step. Light mode
# uses dark grays on the gray background, dark mode light grays on black. Red
# is the wallpaper's ink, paper and vermilion: the red slots (1, 5, 9, 13) carry
# the accent and every other hue is a warm paper tone.
term_fg=$foreground
border=$foreground
case "$mode" in
white)
    muted='#6a6a6a'
    ansi_black=$foreground
    selection='#9a9a9a'
    red='#505050' green='#5e5e5e' yellow='#3c3c3c' blue='#484848'
    magenta='#666666' cyan='#565656'
    bred='#2e2e2e' bgreen='#3a3a3a' byellow='#1e1e1e' bblue='#282828'
    bmagenta='#444444' bcyan='#333333'
    ;;
black)
    term_fg='#e4e4e4'
    muted='#7a7a7a'
    ansi_black='#5c5c5c'
    selection='#3a3a3a'
    red='#a8a8a8' green='#9a9a9a' yellow='#c4c4c4' blue='#b6b6b6'
    magenta='#949494' cyan='#a2a2a2'
    bred='#d0d0d0' bgreen='#c6c6c6' byellow='#e8e8e8' bblue='#dcdcdc'
    bmagenta='#bcbcbc' bcyan='#cccccc'
    ;;
red)
    border='#d94420'
    muted='#7b7963'
    ansi_black='#3a352e'
    selection='#572b1f'
    red='#d94420' green='#b4ab8b' yellow='#e3d4ad' blue='#9a9480'
    magenta='#d55531' cyan='#c8bc98'
    bred='#ef6a45' bgreen='#d4c7a1' byellow='#f3e8c8' bblue='#b8b19a'
    bmagenta='#e8775a' bcyan='#e0d4b0'
    ;;
esac

theme="$HOME/.config/kitty/themes/quickshell.conf"
mkdir -p "${theme%/*}"
tmp=$(mktemp "${theme}.XXXXXX")
trap 'if [[ -e $tmp ]]; then unlink "$tmp"; fi' EXIT
cat > "$tmp" <<EOF
# Generated by Quickshell; do not edit.
background $background
background_opacity $opacity
foreground $term_fg
cursor $term_fg
cursor_text_color $background
selection_foreground $term_fg
selection_background $selection
url_color $blue
active_tab_background $foreground
active_tab_foreground $background
inactive_tab_background $background
inactive_tab_foreground $muted
active_border_color $border
inactive_border_color $muted
# ANSI black must remain visible on the terminal background in both modes.
color0 $ansi_black
color1 $red
color2 $green
color3 $yellow
color4 $blue
color5 $magenta
color6 $cyan
color7 $term_fg
color8 $muted
color9 $bred
color10 $bgreen
color11 $byellow
color12 $bblue
color13 $bmagenta
color14 $bcyan
color15 $term_fg
EOF

# Remember the colours open kitties show now, so they can fade to the new ones.
declare -A old=() new=()
read_colors() { # file array-name
    local -n into=$2
    local key value
    [[ -r $1 ]] || return 0
    while read -r key value; do
        [[ $value =~ ^#[0-9a-fA-F]{6}$ || $key == background_opacity ]] && into[$key]=$value
    done < "$1"
}
read_colors "$theme" old
read_colors "$tmp" new
mv -f "$tmp" "$theme"

sockets=()
# The runtime directory is private to this user. No active kitty is normal.
for socket in "${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"/kitty-quickshell-*; do
    [[ -S $socket ]] && sockets+=("$socket")
done

# Step through in-between colours (~800 ms, matching Theme.qml's fadeDuration),
# all kitties in parallel. The exact theme is applied after the last frame.
frames=14
if (( ${#sockets[@]} )) && [[ ${old[background]:-} && ${old[background]} != "${new[background]}" ]]; then
    for (( f = 1; f < frames; f++ )); do
        args=()
        for key in "${!new[@]}"; do
            [[ $key == background_opacity || -z ${old[$key]:-} ]] && continue
            a=${old[$key]#\#} b=${new[$key]#\#} mix=
            for i in 0 2 4; do
                x=$((16#${a:i:2})) y=$((16#${b:i:2}))
                mix+=$(printf '%02x' $(( x + (y - x) * f / frames )))
            done
            args+=("$key=#$mix")
        done
        opacity_step=$(awk -v a="${old[background_opacity]:-$opacity}" -v b="$opacity" -v t="$f/$frames" \
            'BEGIN { split(t, r, "/"); printf "%.3f", a + (b - a) * r[1] / r[2] }')
        for socket in "${sockets[@]}"; do
            { kitty @ --to "unix:$socket" set-colors --all "${args[@]}"
              kitty @ --to "unix:$socket" set-background-opacity --all "$opacity_step"; } >/dev/null 2>&1 &
        done
        wait
    done
fi

for socket in "${sockets[@]}"; do
    kitty @ --to "unix:$socket" set-colors --all --configured "$theme" >/dev/null 2>&1 || :
    kitty @ --to "unix:$socket" set-background-opacity --all "$opacity" >/dev/null 2>&1 || :
done
